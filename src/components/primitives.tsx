export function Label({ children, className = "" }: { children: ReactNode; className?: string }) {
  return <p className={`label ${className}`}>{children}</p>;
}

/**
 * Section opening. A full-width rule carries the section's name on the left
 * and a factual count on the right; below it the title runs large across
 * eight columns, with the intro set against its baseline on the right.
 */
export function SectionHead({
  id,
  label,
  meta,
  title,
  intro,
}: {
  id: string;
  label: string;
  meta?: string;
  title: ReactNode;
  intro?: ReactNode;
}) {
  return (
    <Reveal>
      <div className="flex items-baseline justify-between gap-6 border-t border-line-strong pt-4">
        <p className="label text-fg">{label}</p>
        {meta && <p className="label">{meta}</p>}
      </div>
      <div className="mt-[clamp(1.75rem,1rem+2.5vw,3.5rem)] grid-12 gap-y-6">
        <h2 id={id} className="text-section col-span-12 max-w-[16ch] lg:col-span-8">
          {title}
        </h2>
        {intro && (
          <div className="text-lead col-span-12 max-w-[40ch] text-fg-2 lg:col-span-4 lg:self-end">{intro}</div>
        )}
      </div>
    </Reveal>
  );
}

export function Reveal({
  as: Tag = "div",
  delay = 0,
  className = "",
  children,
}: {
  as?: "div" | "li" | "article" | "section";
  delay?: number;
  className?: string;
  children: ReactNode;
}) {
  const style = delay ? ({ "--d": `${delay}ms` } as CSSProperties) : undefined;
  return (
    <Tag className={`reveal ${className}`} style={style}>
      {children}
    </Tag>
  );
}

