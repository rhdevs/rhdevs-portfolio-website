/**
 * Responsive portrait. Expects /public{base}-{w}.avif|webp generated by
 * scripts/generate-assets.mjs at full width and half width.
 */
export function Portrait({
  base,
  width,
  height,
  alt,
  sizes,
  className = "",
}: {
  base: string;
  width: number;
  height: number;
  alt: string;
  sizes: string;
  className?: string;
}) {
  const half = Math.round(width / 2);
  const set = (ext: string) => `${base}-${half}.${ext} ${half}w, ${base}-${width}.${ext} ${width}w`;
  return (
    <picture>
      <source type="image/avif" srcSet={set("avif")} sizes={sizes} />
      <img
        src={`${base}-${width}.webp`}
        srcSet={set("webp")}
        sizes={sizes}
        width={width}
        height={height}
        alt={alt}
        loading="lazy"
        decoding="async"
        className={className}
      />
    </picture>
  );
}

/**
 * Headline whose words rise out of their own masks on load (CSS only). The
 * accessible name is the plain string; the space sits outside each masked
 * word because inside an inline-block it would collapse.
 */
export function RiseText({ text }: { text: string }) {
  return (
    <>
      <span className="sr-only">{text}</span>
      {text.split(" ").map((w, i) => (
        <Fragment key={i}>
          {i > 0 && " "}
          <span aria-hidden className="word" style={{ "--i": i } as CSSProperties}>
            <span>{w}</span>
          </span>
        </Fragment>
      ))}
    </>
  );
}

/** A running band at headline size. The second copy is aria-hidden; reduced motion shows one wrapped copy. */
export function Marquee({
  label,
  items,
  seconds = 40,
}: {
  label: string;
  items: { name: string; note?: string }[];
  seconds?: number;
}) {
  const group = (hidden: boolean) => (
    <ul className="marquee-group" aria-hidden={hidden || undefined}>
      {items.map((it) => (
        <li
          key={it.name}
          className="flex items-center gap-[clamp(1.25rem,1rem+1.5vw,2.5rem)] pr-[clamp(1.25rem,1rem+1.5vw,2.5rem)]"
        >
          <span className="text-h2 whitespace-nowrap">{it.name}</span>
          {it.note && (
            <span className="num whitespace-nowrap text-[clamp(1.1rem,0.9rem+1vw,1.75rem)] text-fg-2">{it.note}</span>
          )}
          <img
            src="/brand/logo-64.webp"
            alt=""
            width={64}
            height={64}
            className="size-[clamp(1.5rem,1rem+1.5vw,2.75rem)] opacity-60"
          />
        </li>
      ))}
    </ul>
  );
  return (
    <section
      aria-label={label}
      className="overflow-hidden border-y border-line py-[clamp(1.5rem,1rem+1.5vw,2.75rem)]"
    >
      <div className="marquee" style={{ "--marquee-s": `${seconds}s` } as CSSProperties}>
        {group(false)}
        {group(true)}
      </div>
    </section>
  );
}
